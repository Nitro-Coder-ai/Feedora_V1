-- =============================================================================
-- Feedora — Group chats + WebRTC call signaling (DB-backed, no WebSockets).
-- Tables use IF NOT EXISTS; the MESSAGES ALTERs are guarded in the apply step
-- (MySQL here lacks ADD COLUMN IF NOT EXISTS). Apply with:
--   mysql -uroot -proot -h127.0.0.1 Feedora < scripts/2026_chat_groups_calls.sql
-- =============================================================================

CREATE TABLE IF NOT EXISTS CHAT_GROUPS (
    GROUP_ID INT AUTO_INCREMENT PRIMARY KEY,
    NAME VARCHAR(255) NOT NULL,
    AVATAR_URL VARCHAR(512) NULL,
    AVATAR_PUBLIC_ID VARCHAR(255) NULL,
    CREATED_BY INT NOT NULL,
    CREATED_AT TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
    FOREIGN KEY (CREATED_BY) REFERENCES USERS(USER_ID) ON DELETE CASCADE
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;

CREATE TABLE IF NOT EXISTS CHAT_GROUP_MEMBERS (
    GROUP_ID INT NOT NULL,
    USER_ID INT NOT NULL,
    ROLE VARCHAR(50) DEFAULT 'member',          -- 'admin' | 'member'
    JOINED_AT TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
    PRIMARY KEY (GROUP_ID, USER_ID),
    KEY idx_cgm_user (USER_ID),
    FOREIGN KEY (GROUP_ID) REFERENCES CHAT_GROUPS(GROUP_ID) ON DELETE CASCADE,
    FOREIGN KEY (USER_ID) REFERENCES USERS(USER_ID) ON DELETE CASCADE
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;

CREATE TABLE IF NOT EXISTS CALL_SESSIONS (
    CALL_ID INT AUTO_INCREMENT PRIMARY KEY,
    CALLER_ID INT NOT NULL,
    RECEIVER_ID INT NULL,                        -- NULL for group calls
    GROUP_ID INT NULL,                           -- NULL for direct calls
    CALL_TYPE VARCHAR(20) NOT NULL,              -- 'voice' | 'video'
    STATUS VARCHAR(50) DEFAULT 'ringing',        -- ringing|active|ended|rejected|missed
    OFFER_SDP TEXT NULL,
    ANSWER_SDP TEXT NULL,
    STARTED_AT TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
    ENDED_AT TIMESTAMP NULL,
    KEY idx_call_receiver_status (RECEIVER_ID, STATUS),
    KEY idx_call_group_status (GROUP_ID, STATUS),
    FOREIGN KEY (CALLER_ID) REFERENCES USERS(USER_ID) ON DELETE CASCADE,
    FOREIGN KEY (RECEIVER_ID) REFERENCES USERS(USER_ID) ON DELETE CASCADE,
    FOREIGN KEY (GROUP_ID) REFERENCES CHAT_GROUPS(GROUP_ID) ON DELETE CASCADE
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;

CREATE TABLE IF NOT EXISTS CALL_ICE_CANDIDATES (
    CANDIDATE_ID INT AUTO_INCREMENT PRIMARY KEY,
    CALL_ID INT NOT NULL,
    SENDER_ID INT NOT NULL,
    CANDIDATE TEXT NOT NULL,
    CREATED_AT TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
    KEY idx_ice_call (CALL_ID, CANDIDATE_ID),
    FOREIGN KEY (CALL_ID) REFERENCES CALL_SESSIONS(CALL_ID) ON DELETE CASCADE,
    FOREIGN KEY (SENDER_ID) REFERENCES USERS(USER_ID) ON DELETE CASCADE
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;
